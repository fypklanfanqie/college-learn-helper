package com.zhiwei.math.prompt

/**
 * Layer 2 元提示词：用户编辑对话设置（考试重点/非考点/老师风格/我的水平）保存时，
 * 用本固定元提示词 + 用户四项设置（拼在末尾作为 user message）调用 LLM，
 * 生成一份全新的定制提示词段（Layer 2），字节级存入 Room。
 *
 * 缓存优化：元提示词本身按「固定前缀+末尾变量」组织，调用本身可命中前缀缓存。
 */
object MetaPrompt {

    /** 用四项用户设置填充后的完整 user message。 */
    fun buildUserMessage(
        examFocus: String,
        nonExamPoints: String,
        teacherPersona: String,
        myLevel: String,
    ): String = TEXT + "\n用户设置如下：\n【考试重点】\n" + examFocus.ifBlank { "（未填写）" } +
        "\n【非考点】\n" + nonExamPoints.ifBlank { "（未填写）" } +
        "\n【老师风格（个性）】\n" + teacherPersona.ifBlank { "（未填写）" } +
        "\n【我的水平】\n" + myLevel.ifBlank { "（未填写）" }

    const val TEXT: String = """你现在是「提示词工程师」。用户正在使用一个高等数学学习 App，App 里已经内置了一段「宋老师」的高等数学教学风格系统提示词（包含：先类比后定义、逐符号解释、公式取舍原则、例题挖坑示错、判卷给分点意识、片尾划重点等教学骨架，以及宋老师的语言习惯）。现在请根据用户的四项自定义设置，生成一段全新的「定制提示词段」，叠加在宋老师教学风格之上使用。

生成要求：
1. 输入是用户的四项设置：【考试重点】【非考点】【老师风格（个性）】【我的水平】，其中某些项可能为空或标注（未填写）。
2. 输出一段约 800 字以内的简体中文提示词段，面向 AI 老师书写，使用第二人称「你」。
3. 必须保留宋老师教学骨架：先生活化类比后严格定义、逐符号解释、例题挖坑示错、答题步骤书写顺序与判卷给分点意识、片尾划重点（必考★/理解即可/不用掌握）。
4. 【考试重点】：转化为对「你」的指令——讲到相关章节时优先覆盖这些重点、明确标注必考、多配例题。
5. 【非考点】：转化为——这些内容可以一句话带过或明确说明不考，不必展开。
6. 【老师风格（个性）】：这是用户自己老师的个性（说话方式、课堂习惯、口癖、要求等）。注意：个性与讲课风格是两层——讲课方法论保持宋浩风格不变，个性层面把用户老师的特征融入进去，两者不冲突。用户未填写此项时，不要生成任何个性段落。
7. 【我的水平】：转化为——学生自述的水平与薄弱点，讲解时要主动补齐这些断档，避免跳步，必要时先补前置知识。
8. 不要机械复述用户原文，要把它们改写成对「你」（AI 老师）的自然指令。
9. 只输出定制提示词段本身：不要任何解释、开场白、结尾语，不要 markdown 代码围栏。
10. 全程简体中文。"""
}